"""Pure-Python BIP-340 Schnorr signatures (public keys and secrets as bytes).

This is the crypto backend for FIOR event signing.  It exists because the
previously declared dependency (noble-secp256k1) is not installable on modern
Python.  The implementation follows BIP-340 exactly and is validated against
the official BIP-340 test vectors (self_test()).

All signatures are 64-byte, produced by `sign` and checked by `verify` per
BIP-340.  Nostr pubkeys are the 32-byte X-only representation; `get_pubkey`
returns exactly that.  Nostr event ids are 32 bytes, which is what this module
is used for.
"""

import hashlib
import os

F = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8
G = (GX, GY)

BYTE = 32


def _inv(x: int) -> int:
    return pow(x % F, F - 2, F)


def _add(p1, p2):
    # point at infinity is None
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    x1, y1 = p1
    x2, y2 = p2
    if x1 == x2:
        if (y1 + y2) % F == 0:
            return None
        s = (3 * x1 * x1) * _inv(2 * y1) % F
    else:
        s = (y2 - y1) * _inv(x2 - x1) % F
    x3 = (s * s - x1 - x2) % F
    y3 = (s * (x1 - x3) - y1) % F
    return (x3, y3)


def _mul(k: int, p):
    r = None
    while k:
        if k & 1:
            r = _add(r, p)
        p = _add(p, p)
        k >>= 1
    return r


def lift_x(x: int):
    if x >= F:
        return None
    y = pow((x * x * x + 7) % F, (F + 1) // 4, F)
    if (y * y) % F != (x * x * x + 7) % F:
        return None
    if y % 2 != 0:
        y = F - y  # BIP-340 always lifts to the even-y point
    return (x, y)


def _tagged_hash(tag: str, *msgs: bytes) -> bytes:
    th = hashlib.sha256(tag.encode()).digest()
    h = hashlib.sha256()
    h.update(th)
    h.update(th)
    for m in msgs:
        h.update(m)
    return h.digest()


def get_pubkey(seckey: bytes) -> bytes:
    """32-byte X-only public key for a BIP-340 secret key."""
    d = int.from_bytes(seckey, "big")
    if not 1 <= d <= N - 1:
        raise ValueError("invalid secret key")
    p = _mul(d, G)
    return p[0].to_bytes(BYTE, "big")


def sign(seckey: bytes, msg: bytes, aux: bytes | None = None) -> bytes:
    """BIP-340 Schnorr signature over a message (a 32-byte id in Nostr)."""
    d0 = int.from_bytes(seckey, "big")
    if not 1 <= d0 <= N - 1:
        raise ValueError("invalid secret key")
    if aux is None:
        aux = os.urandom(BYTE)
    if len(aux) != BYTE:
        raise ValueError("aux must be 32 bytes")

    p = _mul(d0, G)
    d = d0 if p[1] % 2 == 0 else N - d0
    px = p[0].to_bytes(BYTE, "big")
    t = bytes(a ^ b for a, b in zip(d.to_bytes(BYTE, "big"), _tagged_hash("BIP0340/aux", aux)))
    k0 = int.from_bytes(_tagged_hash("BIP0340/nonce", t + px + msg), "big") % N
    if k0 == 0:
        raise RuntimeError("bip340: zero nonce")  # astronomically unlikely
    rp = _mul(k0, G)
    k = k0 if rp[1] % 2 == 0 else N - k0
    r = rp[0].to_bytes(BYTE, "big")
    e = int.from_bytes(_tagged_hash("BIP0340/challenge", r + px + msg), "big") % N
    s = (k + e * d) % N
    return r + s.to_bytes(BYTE, "big")


def verify(pubkey: bytes, msg: bytes, sig: bytes) -> bool:
    """Check a BIP-340 signature; accepts any message length, never raises."""
    if len(pubkey) != BYTE or len(sig) != 2 * BYTE:
        return False
    p = lift_x(int.from_bytes(pubkey, "big"))
    if p is None:
        return False
    r = int.from_bytes(sig[:BYTE], "big")
    s = int.from_bytes(sig[BYTE:], "big")
    if r >= F or s >= N:
        return False
    e = int.from_bytes(_tagged_hash("BIP0340/challenge", sig[:BYTE] + pubkey + msg), "big") % N
    rp = _add(_mul(s, G), _mul(N - e, p))
    if rp is None:
        return False
    return rp[0] == r and rp[1] % 2 == 0


def generate_keypair():
    """Fresh random (seckey_bytes, pubkey_bytes)."""
    while True:
        seckey = os.urandom(BYTE)
        if 1 <= int.from_bytes(seckey, "big") <= N - 1:
            return seckey, get_pubkey(seckey)


