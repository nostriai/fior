def self_test() -> bool:
    """True if every embedded vector behaves as the CSV claims: sign matches
    the expected signature where a secret key exists, and verify matches the
    expected result everywhere."""
    for sk, pk, aux, msg, sig, ok in _TEST_VECTORS:
        msg_bytes = bytes.fromhex(msg) if msg else b""
        sig_bytes = bytes.fromhex(sig)
        if sk:
            s = sign(bytes.fromhex(sk), msg_bytes, aux=bytes.fromhex(aux))
            if s.hex().upper() != sig.upper():
                return False
        got = verify(bytes.fromhex(pk), msg_bytes, sig_bytes)
        if got != ok:
            return False
    return True


